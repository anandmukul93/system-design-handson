"""Build site/data/site.json and COVERAGE.md from course.json + concepts.json + the chapter folders.

usage: python tools/build_site_data.py          # write both files
       python tools/build_site_data.py --check  # only validate (used in CI)

Fails if any of the 111 concepts is missing or unmapped, if a concept points at an unknown chapter,
or if a chapter has no README.md or demo/demo.js.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BROWSER_SKIP = ("fastapi", "aiohttp")   # modules importing these can't run in Pyodide and aren't needed by tests


def fail(msg):
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


def main(check_only: bool):
    course = json.loads((ROOT / "course.json").read_text())
    concepts = json.loads((ROOT / "concepts.json").read_text())

    ids = sorted(c["id"] for c in concepts)
    if ids != list(range(1, 112)):
        missing = sorted(set(range(1, 112)) - set(ids))
        fail(f"concepts.json must contain ids 1..111 exactly once (missing: {missing})")

    dirs = {c["num"]: c["dir"] for c in course["chapters"]}
    for c in concepts:
        if not c["chapters"]:
            fail(f"concept {c['id']} {c['name']} is not mapped to any chapter")
        for n in c["chapters"]:
            if n not in dirs:
                fail(f"concept {c['id']} points at unknown chapter {n}")

    chapters = []
    for ch in course["chapters"]:
        d = ROOT / ch["dir"]
        if not (d / "README.md").exists():
            fail(f"{ch['dir']} has no README.md")
        demo = sorted(p.name for p in (d / "demo").glob("*.js"))
        entry = "ui.js" if "ui.js" in demo else "demo.js"
        if entry not in demo:
            fail(f"{ch['dir']} has no demo/ui.js (or demo/demo.js)")
        # tabs: dependencies before the files that import them (depth-first from the entry), entry file last
        order = []

        def visit(name):
            if name in order or name not in demo:
                return
            for dep in re.findall(r'from\s+"\./([^"]+)"', (d / "demo" / name).read_text()):
                if dep != name:
                    visit(dep)
            order.append(name)

        visit(entry)
        demo = order[:-1] + [f for f in demo if f not in order] + [entry]
        py = []
        for p in sorted(d.rglob("*.py")):
            rel = p.relative_to(d).as_posix()
            if rel.startswith("app/") or any(f"import {m}" in p.read_text() or f"from {m}" in p.read_text() for m in BROWSER_SKIP):
                continue
            py.append(rel)
        chapters.append({**ch, "concepts": [c["id"] for c in concepts if ch["num"] in c["chapters"]], "python": py, "demo": demo})

    if check_only:
        print(f"ok: {len(chapters)} chapters, {len(concepts)} concepts mapped")
        return

    out = ROOT / "site" / "data"
    out.mkdir(parents=True, exist_ok=True)
    (out / "site.json").write_text(json.dumps({"phases": course["phases"], "chapters": chapters, "concepts": concepts}, indent=1) + "\n")

    counts = {s: sum(1 for c in concepts if c["status"] == s) for s in ("covered", "deepened", "new")}
    title = {ch["num"]: ch["title"] for ch in course["chapters"]}
    lines = [
        "# Coverage of the 111 concepts",
        "",
        "Generated by `tools/build_site_data.py` from `concepts.json`. Status:",
        "",
        f"- **covered** ({counts['covered']}): built hands-on in chapters 01-28",
        f"- **deepened** ({counts['deepened']}): touched in 01-28 and now also has a dedicated chapter",
        f"- **new** ({counts['new']}): covered by the new chapters 29-51",
        "",
        "The first chapter listed is the concept's main home.",
        "",
        "| # | Concept | Status | Chapters |",
        "|---|---------|--------|----------|",
    ]
    for c in concepts:
        links = ", ".join(f"[{n} {title[n]}]({dirs[n]}/)" for n in c["chapters"])
        lines.append(f"| {c['id']} | {c['name']} | {c['status']} | {links} |")
    (ROOT / "COVERAGE.md").write_text("\n".join(lines) + "\n")
    print(f"wrote site/data/site.json and COVERAGE.md ({len(chapters)} chapters, {counts})")


if __name__ == "__main__":
    main("--check" in sys.argv)
